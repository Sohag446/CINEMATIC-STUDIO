-- ----------------------------------------------------------------------------
-- CINEMATIC STUDIO DATABASE MIGRATION 005: MEDIA ASSETS, TIMELINE & RENDERING
-- ----------------------------------------------------------------------------
-- Forward-only migration adding media asset management, multitrack timeline,
-- non-destructive editing clips, transitions, and render queue jobs.

-- 1. MEDIA ASSETS TABLE (Persistent Project Media Library)
CREATE TABLE IF NOT EXISTS media_assets (
    id TEXT PRIMARY KEY NOT NULL,                                       -- Unique Asset UUID v4
    project_id TEXT NOT NULL,                                           -- FK -> projects.id
    file_name TEXT NOT NULL,                                            -- Original filename
    file_path TEXT NOT NULL,                                            -- Canonical path on disk
    media_type TEXT NOT NULL,                                           -- 'VIDEO', 'AUDIO', 'IMAGE'
    file_size_bytes INTEGER NOT NULL,                                   -- Size in bytes
    duration_seconds REAL,                                              -- Duration in seconds (null for images)
    width INTEGER,                                                      -- Width in pixels (null for audio)
    height INTEGER,                                                     -- Height in pixels (null for audio)
    fps REAL,                                                           -- Constant or nominal frame rate
    video_codec TEXT,                                                   -- e.g. 'h264', 'hevc', 'vp9'
    audio_codec TEXT,                                                   -- e.g. 'aac', 'mp3', 'flac', 'pcm'
    audio_channels INTEGER,                                             -- Channel count (1 = mono, 2 = stereo)
    sample_rate INTEGER,                                                -- e.g. 44100, 48000
    checksum_sha256 TEXT,                                               -- SHA-256 hash for duplicate detection
    thumbnail_path TEXT,                                                -- Generated 160x90 JPEG thumbnail
    proxy_path TEXT,                                                    -- Optional low-res editing proxy
    source_task_id TEXT,                                                -- FK -> tasks.id if generated by AI
    created_at INTEGER NOT NULL,                                        -- Unix epoch milliseconds
    FOREIGN KEY(project_id) REFERENCES projects(id) ON DELETE CASCADE,
    FOREIGN KEY(source_task_id) REFERENCES tasks(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_media_assets_project ON media_assets(project_id, media_type);
CREATE INDEX IF NOT EXISTS idx_media_assets_checksum ON media_assets(checksum_sha256);

-- 2. TIMELINE TRACKS TABLE (Multitrack Layers: V1, V2, A1, A2, Overlay)
CREATE TABLE IF NOT EXISTS timeline_tracks (
    id TEXT PRIMARY KEY NOT NULL,                                       -- Track UUID v4
    project_id TEXT NOT NULL,                                           -- FK -> projects.id
    track_type TEXT NOT NULL,                                           -- 'VIDEO', 'AUDIO', 'OVERLAY'
    track_index INTEGER NOT NULL,                                       -- Track number: 1, 2, etc.
    label TEXT NOT NULL,                                                -- Display label: 'Main Video', 'Dialogue', etc.
    is_muted INTEGER NOT NULL DEFAULT 0,                                -- 1 if muted, 0 otherwise
    is_locked INTEGER NOT NULL DEFAULT 0,                               -- 1 if locked against edits, 0 otherwise
    volume REAL NOT NULL DEFAULT 1.0,                                   -- Track master volume (0.0 to 2.0)
    FOREIGN KEY(project_id) REFERENCES projects(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_timeline_tracks_project ON timeline_tracks(project_id, track_type, track_index);

-- 3. TIMELINE CLIPS TABLE (Non-destructive Editable Clip Instances)
CREATE TABLE IF NOT EXISTS timeline_clips (
    id TEXT PRIMARY KEY NOT NULL,                                       -- Timeline Clip UUID v4
    track_id TEXT NOT NULL,                                             -- FK -> timeline_tracks.id
    project_id TEXT NOT NULL,                                           -- FK -> projects.id
    media_asset_id TEXT NOT NULL,                                       -- FK -> media_assets.id (RESTRICT delete)
    clip_id TEXT,                                                       -- FK -> clips.id if bound to narrative shot
    timeline_start_seconds REAL NOT NULL,                               -- Start time coordinate on timeline
    timeline_duration_seconds REAL NOT NULL,                            -- Duration on timeline
    source_in_seconds REAL NOT NULL DEFAULT 0.0,                        -- Trim start point in source media
    source_out_seconds REAL NOT NULL,                                   -- Trim end point in source media
    volume REAL NOT NULL DEFAULT 1.0,                                   -- Clip volume (0.0 to 2.0)
    fade_in_seconds REAL NOT NULL DEFAULT 0.0,                          -- Audio/Video fade in duration
    fade_out_seconds REAL NOT NULL DEFAULT 0.0,                         -- Audio/Video fade out duration
    z_order INTEGER NOT NULL DEFAULT 0,                                 -- Stacking order within track
    created_at INTEGER NOT NULL,                                        -- Unix epoch milliseconds
    updated_at INTEGER NOT NULL,                                        -- Unix epoch milliseconds
    FOREIGN KEY(track_id) REFERENCES timeline_tracks(id) ON DELETE CASCADE,
    FOREIGN KEY(project_id) REFERENCES projects(id) ON DELETE CASCADE,
    FOREIGN KEY(media_asset_id) REFERENCES media_assets(id) ON DELETE RESTRICT,
    FOREIGN KEY(clip_id) REFERENCES clips(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_timeline_clips_track ON timeline_clips(track_id, timeline_start_seconds);
CREATE INDEX IF NOT EXISTS idx_timeline_clips_project ON timeline_clips(project_id, timeline_start_seconds);

-- 4. TIMELINE TRANSITIONS TABLE
CREATE TABLE IF NOT EXISTS timeline_transitions (
    id TEXT PRIMARY KEY NOT NULL,                                       -- Transition UUID v4
    project_id TEXT NOT NULL,                                           -- FK -> projects.id
    from_clip_id TEXT NOT NULL,                                         -- Preceding timeline clip
    to_clip_id TEXT NOT NULL,                                           -- Succeeding timeline clip
    transition_type TEXT NOT NULL DEFAULT 'CROSSFADE',                  -- 'CROSSFADE', 'DISSOLVE', 'FADE_BLACK', 'WIPE_LEFT'
    duration_seconds REAL NOT NULL DEFAULT 1.0,                         -- Transition duration
    FOREIGN KEY(project_id) REFERENCES projects(id) ON DELETE CASCADE,
    FOREIGN KEY(from_clip_id) REFERENCES timeline_clips(id) ON DELETE CASCADE,
    FOREIGN KEY(to_clip_id) REFERENCES timeline_clips(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_timeline_transitions_proj ON timeline_transitions(project_id);

-- 5. RENDER JOBS TABLE (Persistent FFmpeg Render Queue)
CREATE TABLE IF NOT EXISTS render_jobs (
    id TEXT PRIMARY KEY NOT NULL,                                       -- Render Job UUID v4
    project_id TEXT NOT NULL,                                           -- FK -> projects.id
    preset_name TEXT NOT NULL,                                          -- 'SOCIAL_9_16', 'LANDSCAPE_1080P', 'HIGH_QUALITY_1440P', 'UHD_4K', 'CUSTOM'
    state TEXT NOT NULL DEFAULT 'QUEUED',                               -- 'QUEUED', 'PREPARING', 'VALIDATING', 'RENDERING', 'FINALIZING', 'VERIFYING', 'COMPLETED', 'FAILED', 'CANCELLED'
    output_path TEXT NOT NULL,                                          -- Final destination MP4 path
    progress_percentage REAL NOT NULL DEFAULT 0.0,                      -- 0.0 to 100.0
    current_fps REAL NOT NULL DEFAULT 0.0,                              -- Rendering frame rate
    current_frame INTEGER NOT NULL DEFAULT 0,                           -- Current encoded frame number
    total_frames INTEGER NOT NULL DEFAULT 0,                            -- Expected total frames
    render_strategy TEXT NOT NULL DEFAULT 'NORMALIZING_TRANSCODE',       -- 'STREAM_COPY', 'NORMALIZING_TRANSCODE'
    error_message TEXT,                                                 -- Error diagnostic if failed
    created_at INTEGER NOT NULL,                                        -- Submission epoch ms
    started_at INTEGER,                                                 -- Processing start epoch ms
    completed_at INTEGER,                                               -- Completion epoch ms
    FOREIGN KEY(project_id) REFERENCES projects(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_render_jobs_queue ON render_jobs(state, created_at ASC);
CREATE INDEX IF NOT EXISTS idx_render_jobs_project ON render_jobs(project_id);

